#!/usr/bin/env python3
"""Recover MD32 encoding facts from the public vendor objdump (see doc/research.md).

No vendor executable is needed to build or use the plugin. The SHA256 check
pins the input used to derive the checked-in opcode table.
"""
import argparse
import hashlib
import json
import re
import struct
from pathlib import Path

SHA256 = "ad768602af6c62049ae5338ce390bb4799e6f8c4a78488f64d58b14b4dc4ab04"


class Elf:
    def __init__(self, path):
        self.data = Path(path).read_bytes()
        assert hashlib.sha256(self.data).hexdigest() == SHA256, "Unexpected vendor objdump"
        shoff = struct.unpack_from("<Q", self.data, 40)[0]
        shsize, shnum = struct.unpack_from("<HH", self.data, 58)
        self.sections = [struct.unpack_from("<IIQQQQIIQQ", self.data, shoff + i * shsize)
                         for i in range(shnum)]
        self.symbols = {}
        for sh in self.sections:
            if sh[1] != 2:
                continue
            strings = self.sections[sh[6]]
            names = self.data[strings[4]:strings[4] + strings[5]]
            for off in range(sh[4], sh[4] + sh[5], sh[9]):
                name, _, _, _, addr, size = struct.unpack_from("<IBBHQQ", self.data, off)
                name = names[name:].split(b"\0", 1)[0].decode()
                self.symbols[name] = (addr, size)

    def read(self, addr, size):
        for sh in self.sections:
            if sh[1] != 8 and sh[3] <= addr and addr + size <= sh[3] + sh[5]:
                off = sh[4] + addr - sh[3]
                return self.data[off:off + size]
        raise ValueError(hex(addr))

    def unpack(self, fmt, addr):
        return struct.unpack(fmt, self.read(addr, struct.calcsize(fmt)))

    def string(self, addr):
        out = bytearray()
        while self.read(addr + len(out), 1) != b"\0":
            out += self.read(addr + len(out), 1)
        return out.decode()


def tables(elf):
    rows = []
    base, size = elf.symbols["ms15e30_isa"]
    for off in range(0, size, 24):
        group, addr, _ = elf.unpack("<QQQ", base + off)
        while True:
            code, flags, name, opcode, mask, fmt, count = elf.unpack("<IIQIIII", addr)
            name = elf.string(name)
            if not name:
                break
            args = [elf.unpack("<Ii", addr + 32 + i * 8) for i in range(count)]
            rows.append(dict(group=group, name=name, opcode=opcode, mask=mask,
                             format=fmt, args=args, flags=flags, code=code))
            addr += 80
    return rows


def generate(elf):
    rows = tables(elf)
    used = sorted({a for row in rows for a, shift in row["args"]})
    makers = {addr: name.removesuffix("_maker") for name, (addr, _) in elf.symbols.items()
              if name.endswith("_maker")}
    argtab = elf.symbols["arg_make_table"][0]
    names = {i: makers[elf.unpack("<Q", argtab + 8 * i)[0]] for i in used}
    # Read/write operand variants share the same value decoder.
    unique = sorted(set(names.values()))
    out = ["/* Generated by tools/extract_opcodes.py; encoding facts, see doc/research.md. */",
           "enum {"]
    out += ["\tMD32_" + n.upper() + "," for n in unique]
    out += ["};", "", "static const Md32Opcode md32_opcodes[] = {"]
    for r in rows:
        args = ", ".join("{ MD32_%s, %d }" % (names[a].upper(), shift)
                         for a, shift in r["args"]) or "{ 0, 0 }"
        out.append('\t{ "%s", 0x%08x, 0x%08x, %d, %d, %d, { %s } },' %
                   (r["name"], r["opcode"], r["mask"], r["group"],
                    r["format"], len(r["args"]), args))
    out += ["};", "", "static st32 md32_argument_value(unsigned type, ut32 word, int shift) {",
            "\tut32 x = shift < 0? word: word >> shift;", "\tswitch (type) {"]
    for n in unique:
        if n == "r_c3u":
            expr = "(x & 7) + 1"
        elif n == "r_c4u":
            expr = "x & 15"
        elif n == "r_14":
            expr = "14"
        elif n.startswith("r_"):
            expr = "0"
        elif re.fullmatch(r"i_c[0-9]+", n):
            expr = n[3:]
        elif n in ("i_c9s_2118_0400", "i_c9u_2118_0400"):
            expr = "(word & 31) | ((word >> 13) & 0x1e0)"
            if "9s" in n:
                expr = "md32_sign (" + expr + ", 9)"
        else:
            m = re.fullmatch(r"i_c([0-9]+)(su|s|u)(?:_(n?[0-9]+))?_([0-9]{4})", n)
            assert m, n
            bits, sign, scale, field = m.groups()
            bits = int(bits)
            negative = scale and scale.startswith("n")
            scale = int((scale or "0").removeprefix("n"))
            width = bits - scale - bool(negative)
            expr = "x & 0x%x" % ((1 << width) - 1)
            if scale:
                expr = "(%s) * %d" % (expr, 1 << scale)
            if negative:
                expr = "(%s) - %d" % (expr, 1 << (bits - 1))
            elif sign == "s":
                expr = "md32_sign (%s, %d)" % (expr, bits)
        out += ["\tcase MD32_%s: return %s;" % (n.upper(), expr)]
    out += ["\t}", "\treturn 0;", "}", "",
            "static const char *md32_argument_register(unsigned type) {", "\tswitch (type) {"]
    for n in unique:
        if n.startswith("r_") and n not in ("r_c3u", "r_c4u"):
            out += ['\tcase MD32_%s: return "%s";' % (n.upper(), "r14" if n == "r_14" else n[2:])]
    out += ["\t}", "\treturn NULL;", "}", ""]
    return "\n".join(out)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("objdump")
    p.add_argument("-o", "--output", type=Path)
    p.add_argument("--json", action="store_true")
    args = p.parse_args()
    elf = Elf(args.objdump)
    out = json.dumps(tables(elf), indent=2) + "\n" if args.json else generate(elf)
    if args.output:
        args.output.write_text(out)
    else:
        print(out, end="")


if __name__ == "__main__":
    main()
