#!/usr/bin/env python3
"""Generate mn103_opcodes.h from the GNU binutils MN10300 opcode table (opcodes/m10300-opc.c).

The operand descriptors and the opcode rows are emitted verbatim (same order, same masks,
same format and machine tags) with one exception: the `udfNN` / `udfuNN` placeholder rows
(user-definable slots) are moved after the named rows that share their encoding (`mulq`,
`mulqu`, `swap`, `sat16`, ...), so that a first-match lookup prefers the name over the slot
number when the selected cpu accepts the named row.

usage: gen_mn103_tables.py isa/m10300-opc.c -o mn103_opcodes.h
"""
import argparse
import hashlib
import re

FLAG_NAMES = [
    "DREG", "AREG", "SP", "PSW", "MDR", "SIGNED", "PROMOTE", "PAREN", "REPEATED", "EXTENDED",
    "SPLIT", "REG_LIST", "PCREL", "MEMADDR", "RELAX", "USP", "SSP", "MSP", "PC", "EPSW", "RREG",
    "XRREG", "PLUS", "24BIT", "FSREG", "FDREG", "FPCR",
]
FLAG_VALUE = {n: 1 << i for i, n in enumerate(FLAG_NAMES)}
FMT = ["FMT_S0", "FMT_S1", "FMT_S2", "FMT_S4", "FMT_S6", "FMT_D0", "FMT_D1", "FMT_D2", "FMT_D4",
       "FMT_D5", "FMT_D6", "FMT_D7", "FMT_D8", "FMT_D9", "FMT_D10", "FMT_D3"]
FMT_VALUE = {n: i + 1 for i, n in enumerate(FMT)}
ARCH_VALUE = {"0": 0, "MN103": 300, "AM30": 300, "AM33": 330, "AM33_2": 332}


def parse(src):
    osec = src[src.index("mn10300_operands[] ="):]
    osec = osec[: re.search(r"\n}\s*;", osec).start()]
    names, operands, pending = {}, [], None
    for line in osec.splitlines():
        m = re.match(r"\s*#define\s+(\w+)\s+(?:\(?(\w+)\s*\+\s*1\)?|(\d+))\s*$", line)
        if m and m.group(1) not in ("MEM", "MEMINC", "MEMINC2", "MEM2"):
            pending = m.group(1)
            continue
        m = re.match(r"\s*\{\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*([^}]*)\}", line)
        if m and pending:
            fl = 0
            for tok in re.findall(r"MN10300_OPERAND_(\w+)", m.group(3)):
                fl |= FLAG_VALUE[tok]
            names[pending] = len(operands)
            operands.append((pending, int(m.group(1)), int(m.group(2)), fl))
            pending = None
    env = dict(names)
    env["MEM"] = lambda a: (names["PAREN"], a, names["PAREN"])
    env["MEMINC"] = lambda a: (names["PAREN"], a, names["PLUS"], names["PAREN"])
    env["MEMINC2"] = lambda a, i: (names["PAREN"], a, names["PLUS"], i, names["PAREN"])
    env["MEM2"] = lambda a, b: (names["PAREN"], a, b, names["PAREN"])
    tsec = src[src.index("mn10300_opcodes[] ="):]
    tsec = tsec[: re.search(r"\n}\s*;", tsec).start()]
    rx = re.compile(r'\{\s*"([^"]+)"\s*,\s*(0x[0-9a-fA-F]+|\d+)\s*,\s*(0x[0-9a-fA-F]+|\d+)\s*,'
                    r'\s*(0x[0-9a-fA-F]+|\d+)\s*,\s*(FMT_\w+)\s*,\s*(\w+)\s*,\s*\{([^}]*)\}\s*\}')
    rows = []
    for m in rx.finditer(tsec):
        name, opc, mask, nomatch, fmt, arch, ops = m.groups()
        oplist = []
        for part in re.split(r",(?![^()]*\))", ops.strip()):
            part = part.strip()
            if not part:
                continue
            v = eval(part, {"__builtins__": {}}, env)  # noqa: S307 (table tokens only)
            oplist.extend(v if isinstance(v, tuple) else (v,))
        rows.append((name, int(opc, 0), int(mask, 0), int(nomatch, 0), FMT_VALUE[fmt], ARCH_VALUE[arch], oplist))
    return operands, rows


def reorder(rows):
    """Move the udf placeholder rows after the named rows of the same first byte family."""
    named = [r for r in rows if not re.match(r"udfu?\d\d$", r[0])]
    udf = [r for r in rows if re.match(r"udfu?\d\d$", r[0])]
    return named + udf


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("source")
    ap.add_argument("-o", "--output", required=True)
    a = ap.parse_args()
    data = open(a.source, "rb").read()
    operands, rows = parse(data.decode("utf-8", "replace"))
    rows = reorder(rows)
    out = []
    w = out.append
    w("/* Generated by tools/gen_mn103_tables.py from %s (sha256 %s). Do not edit. */" % (
        a.source.replace("\\", "/").split("/")[-1], hashlib.sha256(data).hexdigest()))
    w("/* The table is the GNU binutils MN10300 opcode table (GPL-3.0-or-later). */")
    w("#ifndef MN103_OPCODES_H")
    w("#define MN103_OPCODES_H")
    w("")
    for n, name in enumerate(FLAG_NAMES):
        w("#define MN103_OPERAND_%s 0x%x" % (name.replace("24BIT", "BIT24"), 1 << n))
    w("")
    for name, v in FMT_VALUE.items():
        w("#define MN103_%s %d" % (name, v))
    w("")
    w("#define MN103_MACH_BASE 0")
    w("#define MN103_MACH_AM30 300")
    w("#define MN103_MACH_AM33 330")
    w("#define MN103_MACH_AM33_2 332")
    w("")
    for i, (name, bits, shift, fl) in enumerate(operands):
        w("#define MN103_OP_%s %d" % (name, i))
    w("")
    w("typedef struct {")
    w("\tconst char *name;")
    w("\tut8 bits;")
    w("\tst8 shift;")
    w("\tut32 flags;")
    w("} Mn103OperandDesc;")
    w("")
    w("typedef struct {")
    w("\tconst char *name;")
    w("\tut32 opcode;")
    w("\tut32 mask;")
    w("\tut32 no_match;")
    w("\tut8 format;")
    w("\tut16 machine;")
    w("\tut8 nops;")
    w("\tut8 ops[6];")
    w("} Mn103Opcode;")
    w("")
    w("#ifndef MN103_OPCODES_NO_TABLE")
    w("static const Mn103OperandDesc mn103_operands[%d] = {" % len(operands))
    for name, bits, shift, fl in operands:
        w('\t{ "%s", %d, %d, 0x%x },' % (name, bits, shift, fl))
    w("};")
    w("")
    w("static const Mn103Opcode mn103_opcodes[%d] = {" % len(rows))
    for name, opc, mask, nomatch, fmt, arch, ops in rows:
        opl = ", ".join("MN103_OP_%s" % operands[o][0] for o in ops) or "0"
        w('\t{ "%s", 0x%x, 0x%x, 0x%x, %d, %d, %d, { %s } },' % (name, opc, mask, nomatch, fmt, arch, len(ops), opl))
    w("};")
    w("#endif")
    w("")
    w("#endif")
    open(a.output, "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
